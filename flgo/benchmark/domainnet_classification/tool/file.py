# Process data
data_dict = {}
current_category = None

for line in data_text.strip().split("\n"):
    if line in categories:
        current_category = line
        data_dict[current_category] = []
    else:
        parts = line.split()
        item_name = " ".join(parts[:-7])
        values = list(map(int, parts[-7:]))
        data_dict[current_category].append([item_name] + values)

# Column names
columns = ["Item", "clp", "inf", "pnt", "qdr", "rel", "skt", "total"]

# Create Excel file
